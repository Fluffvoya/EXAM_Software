#include "menu.h"
#include "LED_demo.h"
#include "OLED.h"
#include "anime_demo.h"
#include "image_demo.h"

uint8_t menu_state = 0;
uint8_t is_entered = 0;

#define MENU_NUMBER 4

void MenuNext() {
  if (is_entered)
    return;
  menu_state += 1;
  menu_state %= 4;
  ShowMenu();
}
void MenuPrev() {
  if (is_entered)
    return;
  if (menu_state == 0)
    menu_state = MENU_NUMBER - 1;
  else
    menu_state -= 1;
  menu_state %= 4;
  ShowMenu();
}

void EnterItem() {
  if (is_entered)
    return;
  is_entered = 1;
  if (menu_state == 0) {
    EnterLED();
  } else if (menu_state == 1) {
    EnterImage();
  } else if (menu_state == 2) {
    EnterAnime();
  } else if (menu_state == 3) {
    is_entered = 0;
  }
}
void ExitItem() {
  if (!is_entered)
    return;
  is_entered = 0;
  if (menu_state == 0) {
    ExitLED();
  } else if (menu_state == 1) {
    ExitImage();
  } else if (menu_state == 2) {
    ExitAnime();
  } else if (menu_state == 3) {
    is_entered = 1;
  }
  ShowMenu();
}

